/// Masked array for a selector. Unknown selectors map to an empty slice, so
/// a Dart/Rust selector-table drift degrades to an empty string, never a
/// panic. Keep these numbers in sync with `rust_vault.dart`.
fn masked(sel: u32) -> &'static [u8] {
    match sel {
        1 => V_VERDICT_URL,
        2 => V_GCD_BASE,
        3 => V_DEV_KEY,
        4 => V_PROJECT_NUMBER,

        10 => V_UA_PRODUCT,
        11 => V_UA_PLATFORM_OPEN,
        12 => V_UA_BUILD_TAG,
        13 => V_UA_PLATFORM_CLOSE,
        14 => V_UA_ENGINE_TAG,
        15 => V_UA_ENGINE_TAIL,
        16 => V_UA_CHROME_TAG,
        17 => V_UA_SAFARI_TAG,
        18 => V_CHROME_BUILD,
        19 => V_WEBKIT_BUILD,

        30 => V_JS_VIEWPORT,
        31 => V_JS_KEYBOARD,
        32 => V_JS_AUTOPLAY,
        33 => V_JS_SEAT_HOOK,

        40 => V_NOTIFY_TITLE,
        41 => V_NOTIFY_SUBTITLE,
        42 => V_NO_SIGNAL_TITLE,
        43 => V_NO_SIGNAL_BODY,
        44 => V_LABEL_ACCEPT,
        45 => V_LABEL_SKIP,
        46 => V_LABEL_RETRY,

        50 => V_NOTIFY_SNOOZE_SECONDS,

        60 => V_FB_API_KEY,
        61 => V_FB_APP_ID,
        62 => V_FB_PROJECT_ID,
        63 => V_FB_STORAGE_BUCKET,

        _ => &[],
    }
}

/// Decoded plaintext bytes for a selector.
pub fn bytes(sel: u32) -> Vec<u8> {
    mask::unmask(masked(sel))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ua_product_decodes() {
        assert_eq!(bytes(10), b"Mozilla/5.0");
    }

    #[test]
    fn copy_decodes() {
        assert_eq!(bytes(41), b"Stay tuned for special offers and rewards");
        assert_eq!(bytes(50), b"258864");
    }

    #[test]
    fn unknown_selector_is_empty() {
        assert!(bytes(9999).is_empty());
    }

    #[test]
    fn empty_slots_stay_empty() {
        assert!(bytes(30).is_empty());
    }

    #[test]
    fn firebase_options_decode() {
        // Assert the round-trip and the internal shape (appId embeds the
        // sender id, bucket embeds the project id) without hardcoding the
        // credentials as greppable literals in source.
        let api = String::from_utf8(bytes(60)).unwrap();
        let app = String::from_utf8(bytes(61)).unwrap();
        let sender = String::from_utf8(bytes(4)).unwrap();
        let project = String::from_utf8(bytes(62)).unwrap();
        let bucket = String::from_utf8(bytes(63)).unwrap();
        assert!(api.starts_with("AIza") && api.len() > 30);
        assert!(app.starts_with(&format!("1:{}:android:", sender)));
        assert!(!project.is_empty());
        assert!(bucket.starts_with(&project));
    }

    #[test]
    fn keyboard_hook_decodes() {
        // The seat hook is the global function name the JS body defines and
        // the Flutter side calls; the body must reference the same name.
        let hook = String::from_utf8(bytes(33)).unwrap();
        assert_eq!(hook, "swSeatField");
        let body = String::from_utf8(bytes(31)).unwrap();
        assert!(body.contains(&format!("w.{}=function", hook)));
        assert!(body.starts_with("(function(w,d){"));
    }
}
